import { useMemo, useState } from "react";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { JsonCode } from "@/components/JsonCode";
import { modelColor } from "@/lib/presentation";
import { TEAM_COLORS, type Run } from "@/lib/run";

const PAGE_SIZE = 10;
const yesNo = (value: boolean) => (value ? "Yes" : "No");

export function Dataset({ run }: { run: Run }) {
  const [q, setQ] = useState("");
  const [team, setTeam] = useState("");
  const [page, setPage] = useState(0);
  const [selected, setSelected] = useState<number | null>(null);
  const rows = useMemo(() => {
    const needle = q.trim().toLowerCase();
    return run.tickets.filter(
      (t) =>
        (!team || t.label.team === team) &&
        (!needle || `${t.subject} ${t.body}`.toLowerCase().includes(needle)),
    );
  }, [q, team, run.tickets]);
  const pages = Math.max(1, Math.ceil(rows.length / PAGE_SIZE));
  const visible = rows.slice(page * PAGE_SIZE, (page + 1) * PAGE_SIZE);

  return (
    <Card className="report-panel">
      <h2>Explore the {run.tickets.length} tickets</h2>
      <p className="figure-note">
        Synthetic tickets generated by Claude Haiku 4.5 from assigned labels.
        Open a ticket to read the message and compare the models' answers below
        it.
      </p>
      <div className="dataset-filters">
        <label>
          Search tickets
          <input
            value={q}
            onChange={(e) => {
              setQ(e.target.value);
              setPage(0);
            }}
            placeholder="Search subject or message"
            type="search"
          />
        </label>
        <label>
          Generated team label
          <select
            value={team}
            onChange={(e) => {
              setTeam(e.target.value);
              setPage(0);
            }}
          >
            <option value="">All teams</option>
            {Object.keys(TEAM_COLORS).map((t) => (
              <option key={t} value={t}>
                {t[0].toUpperCase() + t.slice(1)}
              </option>
            ))}
          </select>
        </label>
      </div>
      <p className="text-sm text-muted-foreground" role="status">
        {rows.length
          ? `${page * PAGE_SIZE + 1}–${Math.min((page + 1) * PAGE_SIZE, rows.length)} of ${rows.length} tickets.`
          : "No tickets match your search."}{" "}
        Filters use the original labels, not model answers.
      </p>
      <div className="ticket-list">
        {visible.map((t) => (
          <article key={t.id} className="ticket-row">
            <h3>
              <button
                type="button"
                id={`ticket-${t.id}`}
                aria-expanded={selected === t.id}
                aria-controls={`ticket-details-${t.id}`}
                className="ticket-toggle"
                onClick={() => setSelected(selected === t.id ? null : t.id)}
              >
                <span className="ticket-id">#{t.id}</span>
                <span className="min-w-0 flex-1">
                  <span className="block font-semibold">{t.subject}</span>
                  <span className="ticket-preview">{t.body}</span>
                </span>
                <span className="ticket-team">{t.label.team}</span>
                <span className="ticket-chevron" aria-hidden="true">
                  {selected === t.id ? "−" : "+"}
                </span>
              </button>
            </h3>
            <div
              id={`ticket-details-${t.id}`}
              role="region"
              aria-labelledby={`ticket-${t.id}`}
              hidden={selected !== t.id}
            >
              {selected === t.id && <Inspector run={run} id={t.id} />}
            </div>
          </article>
        ))}
        {rows.length === 0 && (
          <div className="p-6">
            <p>Try a different search or choose another team.</p>
            <Button
              className="mt-3"
              variant="outline"
              onClick={() => {
                setQ("");
                setTeam("");
                setPage(0);
              }}
            >
              Clear filters
            </Button>
          </div>
        )}
      </div>
      <div
        className="flex flex-wrap items-center justify-between gap-3 pt-2"
        aria-label="Dataset pagination"
      >
        <Button
          variant="outline"
          disabled={page === 0}
          onClick={() => {
            setPage(page - 1);
            setSelected(null);
          }}
        >
          Previous
        </Button>
        <span className="text-sm text-muted-foreground">
          Page {page + 1} of {pages}
        </span>
        <Button
          variant="outline"
          disabled={page >= pages - 1}
          onClick={() => {
            setPage(page + 1);
            setSelected(null);
          }}
        >
          Next
        </Button>
      </div>
    </Card>
  );
}

function Inspector({ run, id }: { run: Run; id: number }) {
  const t = run.tickets.find((x) => x.id === id)!;
  const jev = run.lanes
    .find((l) => l.key === "jev")
    ?.results.find((r) => r.id === id)?.raw;
  return (
    <div className="ticket-details">
      <h4 className="font-semibold">Customer message</h4>
      <p className="mt-2 max-w-4xl whitespace-pre-wrap leading-relaxed">
        {t.body}
      </p>
      <h4 className="mt-6 font-semibold">Model answers</h4>
      <p className="mt-1 text-sm text-muted-foreground">
        These are the decisions used for agreement scoring. Urgency runs from 0
        to 3.
      </p>
      <div
        className="mt-3 overflow-x-auto"
        tabIndex={0}
        role="region"
        aria-label="Model answers comparison"
      >
        <table className="comparison-table">
          <thead>
            <tr>
              <th>Model</th>
              <th>Team</th>
              <th>Urgency</th>
              <th>Refund?</th>
              <th>Angry?</th>
              <th>Latency</th>
            </tr>
          </thead>
          <tbody>
            {run.lanes.map((lane) => {
              const r = lane.results.find((result) => result.id === id);
              return (
                <tr key={lane.key}>
                  <th scope="row">
                    <span
                      className="model-dot"
                      style={{ background: modelColor(lane.key) }}
                    />
                    {lane.label}
                  </th>
                  {r?.verdict ? (
                    <>
                      <td>{r.verdict.team}</td>
                      <td>{r.verdict.urgency}</td>
                      <td>{yesNo(r.verdict.refund_requested)}</td>
                      <td>{yesNo(r.verdict.angry)}</td>
                      <td className="whitespace-nowrap">
                        {r.ms.toFixed(0)} ms
                      </td>
                    </>
                  ) : (
                    <td colSpan={5}>
                      {r?.error
                        ? `Request failed: ${r.error}`
                        : "No answer recorded"}
                    </td>
                  )}
                </tr>
              );
            })}
            <tr className="reference-row">
              <th scope="row">Generated label</th>
              <td>{t.label.team}</td>
              <td>{t.label.urgency}</td>
              <td>{yesNo(t.label.refund_requested)}</td>
              <td>{yesNo(t.label.angry)}</td>
              <td>Not applicable</td>
            </tr>
          </tbody>
        </table>
      </div>
      <p className="mt-3 text-sm text-muted-foreground">
        The generated label describes the intended scenario. It has not been
        verified by a human reviewer.
      </p>
      {jev && (
        <details className="mt-5">
          <summary className="cursor-pointer py-2 font-medium">
            Jev's scores before conversion
          </summary>
          <dl className="raw-values">
            <div>
              <dt>Team confidence</dt>
              <dd>{(jev.team_confidence * 100).toFixed(1)}%</dd>
            </div>
            <div>
              <dt>Urgency score</dt>
              <dd>{jev.urgency_score.toFixed(2)} / 3</dd>
            </div>
            <div>
              <dt>Refund probability</dt>
              <dd>{jev.refund_p.toFixed(3)}</dd>
            </div>
            <div>
              <dt>Anger probability</dt>
              <dd>{jev.angry_p.toFixed(3)}</dd>
            </div>
          </dl>
          <p className="mt-3 text-sm text-muted-foreground">
            Urgency is rounded to the nearest integer. Probabilities at or above
            0.5 become “Yes.” The LLM schema requests whole numbers and
            booleans, not probabilities.
          </p>
        </details>
      )}
    </div>
  );
}

export function Requests({
  requests,
}: {
  requests: { jev: unknown; llm: unknown };
}) {
  const [tab, setTab] = useState<"jev" | "llm">("jev");
  const [copyStatus, setCopyStatus] = useState("");
  return (
    <Card className="report-panel">
      <h2>Recorded API requests</h2>
      <p className="figure-note">
        Request bodies for ticket 0. Jev receives typed questions; the LLMs
        receive a prompt and a strict JSON schema. Both use the same task
        definitions.
      </p>
      <div className="flex flex-wrap items-center justify-between gap-3 mt-3">
        <div className="flex gap-2" role="group" aria-label="Request format">
          {(["jev", "llm"] as const).map((key) => (
            <Button
              key={key}
              variant={tab === key ? "secondary" : "outline"}
              aria-pressed={tab === key}
              onClick={() => {
                setTab(key);
                setCopyStatus("");
              }}
            >
              {key === "jev" ? "Jev" : "LLM"}
            </Button>
          ))}
        </div>
        <Button
          variant="outline"
          onClick={async () => {
            try {
              await navigator.clipboard.writeText(
                JSON.stringify(requests[tab], null, 2),
              );
              setCopyStatus("Copied to clipboard.");
            } catch {
              setCopyStatus(
                "Copy unavailable. Select the code to copy it manually.",
              );
            }
          }}
        >
          Copy JSON
        </Button>
      </div>
      <p className="request-endpoint">
        <span>POST</span>{" "}
        {tab === "jev" ? "/api/alpha/decisions" : "/api/v1/chat/completions"}
      </p>
      {copyStatus && (
        <p role="status" className="text-sm">
          {copyStatus}
        </p>
      )}
      <JsonCode value={requests[tab]} />
    </Card>
  );
}
